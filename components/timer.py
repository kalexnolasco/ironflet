"""Rest timer (async, no threading) with an audible end-of-rest alert.

The countdown used to finish in silence, which meant looking at the phone to
know when the rest was over — awkward when the phone is on the floor or in a
pocket. It now beeps twice: once ten seconds out ("get ready") and once at zero
("go"), plus a vibration where the platform supports one.

The alert is best-effort by construction. A browser that refuses to play, an
audio control that never mounted, a database that cannot answer whether sound
is even wanted — none of it may reach the countdown, which is the part Alex is
actually relying on. Every call into Flet or into storage below is wrapped.

Tones live in `assets/sounds/` and are generated by `scripts/make_timer_sounds.py`;
that file documents the frequencies and durations and why they were chosen.
"""

from __future__ import annotations

import asyncio
import contextlib
import warnings
from pathlib import Path

import flet as ft

from theme import C, Radius

#: Seconds between ticks. A module constant rather than a literal so a test can
#: drive a whole countdown in milliseconds instead of sitting through minutes.
TICK_S = 1.0

#: How far from the end the "get ready" beep fires.
PRE_ALERT_S = 10

#: …and the shortest rest that gets one. On a 15 s rest the warning would land
#: before the phone is back on the floor, which is noise, not information.
PRE_ALERT_MIN_TOTAL_S = 25

#: Preference keys. Values are the strings "on"/"off"; anything unrecognised —
#: including a missing row — reads as "on", because a user who has never opened
#: the setting has not asked for silence.
SOUND_PREF = "timer_sound"
HAPTICS_PREF = "timer_haptics"

#: Sizes for the two layouts this timer can render into. `build()` and
#: `build_large()` hand out the **same** control objects — the countdown loop
#: mutates them by reference — so each layout has to restate every geometry the
#: other one changes. Leave a size out of `build()` and switching zen mode off
#: leaves a 36 pt countdown inside a 56 px ring, which is how the digits ended
#: up clipped the first time this was written.
RING_PX, DISPLAY_PT = 56, 14
RING_PX_LARGE, DISPLAY_PT_LARGE = 128, 36

#: `main.py` passes `assets_dir="assets"`, so Flet serves this directory at the
#: web root and the src is an app-relative URL. It must NOT be a filesystem
#: path: a `file://` src is refused by the browser ("Not allowed to load local
#: resource") and the app is deployed in web mode — the same trap that made
#: every exercise image invisible once.
SOUNDS_DIR = Path(__file__).resolve().parent.parent / "assets" / "sounds"
WARN_SOUND = "/sounds/rest_warning.wav"
DONE_SOUND = "/sounds/rest_done.wav"


# ── preferences (public: other views drive the same switch) ───


def _pref_on(store, key: str) -> bool:
    """Read an on/off preference, defaulting to on and never raising."""
    if store is None:
        return True
    try:
        raw = store.get_pref(key, "on")
    except Exception:
        # The rest timer keeps working when the database does not. Failing
        # open is the safe direction: worst case a beep the user muted.
        return True
    return (raw or "on").strip().lower() not in ("off", "0", "false", "no")


def _set_pref_on(store, key: str, enabled: bool) -> None:
    if store is None:
        return
    with contextlib.suppress(Exception):
        store.set_pref(key, "on" if enabled else "off")


def sound_enabled(store) -> bool:
    """Is the rest-timer beep wanted? Default yes."""
    return _pref_on(store, SOUND_PREF)


def set_sound_enabled(store, enabled: bool) -> None:
    _set_pref_on(store, SOUND_PREF, enabled)


def haptics_enabled(store) -> bool:
    """Is the rest-timer vibration wanted? Default yes."""
    return _pref_on(store, HAPTICS_PREF)


def set_haptics_enabled(store, enabled: bool) -> None:
    _set_pref_on(store, HAPTICS_PREF, enabled)


# ── the Flet audio control ────────────────────────────────────


def _make_audio(src: str):
    """Build an audio control, preferring the `flet-audio` package.

    Flet 0.26 moved `Audio` out of core into `flet-audio` and left a deprecated
    shim behind, scheduled for deletion in 0.29 — inside this project's own
    `flet[all]>=0.25,<0.30` pin. So try the package first and fall back to the
    shim, with the DeprecationWarning silenced: it fires on *every* rest and
    there is nothing the user can do about it.

    The package is deliberately NOT a dependency here. `uv pip install
    flet-audio` resolves to 0.86.5 and drags flet 0.86 with it, which breaks the
    pin and wipes the vendored CanvasKit; the pinned-compatible `flet-audio==0.1.0`
    installs cleanly but `uv sync` prunes anything absent from pyproject.toml,
    so the shim has to work regardless. It does: the prebuilt `flet_web` client
    already bundles `audioplayers_web` and registers the `audio` control, which
    is the only side that has to understand it in web mode.
    """
    try:
        from flet_audio import Audio  # type: ignore[import-not-found]

        return Audio(src=src, autoplay=False, volume=1.0)
    except ImportError:
        pass
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", DeprecationWarning)
        return ft.Audio(src=src, autoplay=False, volume=1.0)


class RestTimer:
    def __init__(self, page: ft.Page, store=None):
        self.page = page
        # Optional: `main.py` builds the views *before* filling `page.data`, so
        # a store cannot be read in __init__ — see `_store()`.
        self._store = store
        self.seconds = 0
        self.running = False
        self.total = 0
        self._tick_id = 0

        # Alert state. Both hold the `_tick_id` generation an alert already
        # fired for, so a restart (which bumps `_tick_id`) can never replay the
        # alert of the countdown it replaced, and a stale loop cannot double it.
        self._warned_tick: int | None = None
        self._done_tick: int | None = None

        self._sound_on = True
        self._haptics_on = True
        self._prefs_loaded = False

        self._players: dict[str, object] = {}
        self._haptics: ft.HapticFeedback | None = None
        self._mounted = False

        self.display = ft.Text("REST", size=DISPLAY_PT, weight=ft.FontWeight.W_800, color=C.accent)
        self.ring = ft.ProgressRing(
            width=RING_PX,
            height=RING_PX,
            stroke_width=4,
            color=C.accent,
            bgcolor=C.border,
            value=0,
        )
        self.stop_btn = ft.TextButton(
            "Stop",
            on_click=lambda _: self.stop(),
            style=ft.ButtonStyle(color=C.accent_2),
            visible=False,
        )
        self.sound_btn = ft.Container(
            content=ft.Icon(ft.Icons.VOLUME_UP_ROUNDED, size=16, color=C.text_secondary),
            bgcolor=C.bg_sunken,
            border=ft.border.all(1, C.border),
            border_radius=Radius.sm,
            padding=ft.padding.symmetric(horizontal=8, vertical=5),
            tooltip="Rest alert sound",
            on_click=lambda _: self.toggle_sound(),
        )

    # ── preferences ───────────────────────────────────────────
    @property
    def sound_on(self) -> bool:
        return self._sound_on

    @property
    def haptics_on(self) -> bool:
        return self._haptics_on

    def _store_ref(self):
        """The shared Storage, resolved late.

        `main.py` constructs `WorkoutView` (and therefore this) at line 42 but
        only assigns `page.data` at line 113, so this lookup cannot happen in
        __init__ — it would find nothing and cache the nothing.
        """
        if self._store is None:
            data = getattr(self.page, "data", None)
            if isinstance(data, dict):
                self._store = data.get("store")
        return self._store

    def _load_prefs(self, force: bool = False) -> None:
        """Refresh the cached on/off flags from storage.

        Called once per rest rather than once per tick: each read is a database
        round-trip and the answer cannot change mid-countdown in a way that
        matters. It is also refreshed lazily on the first `build()` so the
        button shows the truth, and after any change made elsewhere (the
        Profile screen) it is picked up at the next `start()`.
        """
        if self._prefs_loaded and not force:
            return
        store = self._store_ref()
        self._sound_on = sound_enabled(store)
        self._haptics_on = haptics_enabled(store)
        self._prefs_loaded = True

    def toggle_sound(self) -> None:
        """Flip the beep on/off and persist it. Wired to the speaker button."""
        self._sound_on = not self._sound_on
        set_sound_enabled(self._store_ref(), self._sound_on)
        self._prefs_loaded = True
        self._style_sound_btn()
        with contextlib.suppress(Exception):
            self.page.update()

    def _style_sound_btn(self) -> None:
        icon = self.sound_btn.content
        if isinstance(icon, ft.Icon):
            icon.name = (
                ft.Icons.VOLUME_UP_ROUNDED if self._sound_on else ft.Icons.VOLUME_OFF_ROUNDED
            )
            icon.color = C.accent if self._sound_on else C.text_muted
        self.sound_btn.bgcolor = C.accent_soft if self._sound_on else C.bg_sunken
        self.sound_btn.border = ft.border.all(1, C.border)
        self.sound_btn.tooltip = (
            "Rest alert sound: on" if self._sound_on else "Rest alert sound: off"
        )

    # ── alerts ────────────────────────────────────────────────
    def _audio_is_renderable(self) -> bool:
        """Can the client on the other end actually draw an `audio` control?

        Web can: `flet_web` ships the audioplayers plugin. A `flet build` APK
        cannot — `flet-audio` only exists for the 0.86 line, which would drag
        flet 0.86 in and break the 0.28 pin. So on Android there is no sound,
        and pretending otherwise costs a red error panel across the screen.
        """
        try:
            plataforma = getattr(self.page, "platform", None)
            if plataforma is not None and str(plataforma).upper().endswith("ANDROID"):
                return False
            # An installed flet_audio means a client that understands it.
            import flet_audio  # noqa: F401

            return True
        except ImportError:
            # Web falls through to here and must still get sound: the browser
            # client bundles the plugin even when the Python package is absent.
            return bool(getattr(self.page, "web", False))
        except Exception:
            return False

    def _mount_players(self) -> None:
        """Create the audio/haptic controls and put them in `page.overlay`, once.

        Done from `start()`, which is always inside a user gesture (a preset
        chip, or "Save & Next"). That matters for browsers: Chrome and Firefox
        allow programmatic playback on any document the user has already
        interacted with — which by then is guaranteed, you cannot reach a rest
        without tapping something — while Safari gates it per media element,
        so creating the element during the gesture is the friendliest moment.
        Even so, playback is treated as allowed to fail; see `_alert`.
        """
        if self._mounted:
            return
        # Set first: if this fails there is no point retrying on the next rest,
        # and retrying would append duplicate controls to the overlay.
        self._mounted = True
        try:
            overlay = self.page.overlay
            # Audio ONLY where a client can render it. The prebuilt `flet_web`
            # bundles `audioplayers_web` and knows the `audio` control; the APK
            # client does not, and an unknown control is not ignored — Flet
            # paints a red "Unknown control: audio" panel over a third of the
            # screen. Found by running the APK on an emulator, with the whole
            # suite green: nothing in Python can see what the Dart side refuses
            # to build.
            if self._audio_is_renderable():
                for src in (WARN_SOUND, DONE_SOUND):
                    control = _make_audio(src)
                    self._players[src] = control
                    overlay.append(control)
            # Haptics are core Flet, so they render everywhere — and in a noisy
            # gym a buzz beats a beep anyway. On Android this is the whole alert.
            self._haptics = ft.HapticFeedback()
            overlay.append(self._haptics)
            self.page.update()
        except Exception:
            # A timer with no alert is degraded, not broken.
            self._players.clear()
            self._haptics = None

    def _play(self, src: str) -> None:
        """Fire one sound. The seam the tests replace: logic above, Flet below."""
        player = self._players.get(src)
        if player is not None:
            player.play()

    def _vibrate(self, src: str) -> None:
        """Buzz. Heavy for "go", light for the warning — in a pocket, the two
        have to be distinguishable without looking.

        Real on Android and iOS. On web this is a no-op: Flutter web does not
        implement the haptics platform channel, so the call is swallowed by the
        engine without error. Kept anyway because it costs one control, it is
        the *better* signal in a loud gym, and it starts working the day this
        is packaged as an APK — which is what `[tool.flet.android]` is for.
        """
        if self._haptics is None:
            return
        if src == DONE_SOUND:
            self._haptics.heavy_impact()
        else:
            self._haptics.light_impact()

    def _alert(self, src: str) -> None:
        """Sound + vibration for one event. Never raises.

        Called from the tick loop, so nothing here may propagate: a browser
        blocking autoplay, a control that is not mounted yet, or a player that
        throws must all leave the countdown ticking and the console clean.
        """
        if self._sound_on:
            with contextlib.suppress(Exception):
                self._play(src)
        if self._haptics_on:
            with contextlib.suppress(Exception):
                self._vibrate(src)

    # ── countdown ─────────────────────────────────────────────
    def start(self, secs: int):
        self.total = secs
        self.seconds = secs
        self.running = True
        self.ring.value = 0
        self.display.value = f"{secs // 60}:{secs % 60:02d}"
        self.stop_btn.visible = True
        self._tick_id += 1
        tick_id = self._tick_id
        # Once per rest, not once per tick.
        self._load_prefs(force=True)
        self._style_sound_btn()
        self._mount_players()
        self.page.update()
        self.page.run_task(self._tick_loop, tick_id)

    def stop(self):
        self.running = False
        self.seconds = 0
        self.display.value = "REST"
        self.ring.value = 0
        self.stop_btn.visible = False
        # Invalidate the running loop so a manual stop cannot fall through to
        # the "GO!" branch and beep at someone who just cancelled the rest.
        self._tick_id += 1
        self.page.update()

    async def _tick_loop(self, tick_id: int):
        # Armed once, from the total: a rest too short for a ten-second warning
        # simply never gets one.
        warn_at = PRE_ALERT_S if self.total >= PRE_ALERT_MIN_TOTAL_S else -1
        while self.running and self.seconds > 0 and tick_id == self._tick_id:
            await asyncio.sleep(TICK_S)
            if tick_id != self._tick_id or not self.running:
                return
            self.seconds -= 1
            m, s = divmod(max(self.seconds, 0), 60)
            self.display.value = f"{m}:{s:02d}"
            self.ring.value = (self.total - self.seconds) / self.total if self.total else 0
            # `<=`, not `==`: a busy event loop can swallow a second and the
            # warning would be skipped entirely. The generation guard is what
            # keeps it from firing on every remaining tick.
            if 0 < self.seconds <= warn_at and self._warned_tick != tick_id:
                self._warned_tick = tick_id
                self._alert(WARN_SOUND)
            self.page.update()
        if tick_id == self._tick_id and self.seconds <= 0 and self.running:
            self.running = False
            self.display.value = "GO!"
            self.ring.value = 1
            self.stop_btn.visible = False
            if self._done_tick != tick_id:
                self._done_tick = tick_id
                self._alert(DONE_SOUND)
            self.page.update()

    # ── render ────────────────────────────────────────────────
    def _preset(self, label: str, secs: int) -> ft.Control:
        return ft.Container(
            content=ft.Text(label, size=11, weight=ft.FontWeight.W_700, color=C.text_secondary),
            bgcolor=C.bg_sunken,
            border=ft.border.all(1, C.border),
            border_radius=8,
            padding=ft.padding.symmetric(horizontal=10, vertical=6),
            on_click=lambda _, s=secs: self.start(s),
        )

    def _restyle(self, *, ring_px: int, display_pt: int, stroke: int) -> None:
        """Re-apply everything a layout owns, before handing the controls out.

        These controls outlive a render — they are created once in `__init__`
        and both layouts reuse the very same objects — so colours are re-read
        to follow the palette, and geometry is restated because the *other*
        layout may have left its own numbers behind.
        """
        self.display.color = C.accent
        self.display.size = display_pt
        self.ring.color = C.accent
        self.ring.bgcolor = C.border
        self.ring.width = self.ring.height = ring_px
        self.ring.stroke_width = stroke
        self.stop_btn.style = ft.ButtonStyle(color=C.accent_2)
        # Lazily, so the speaker button shows the stored state on the first
        # render instead of guessing "on"; afterwards the in-process value is
        # trusted and only `start()` goes back to the database.
        self._load_prefs()
        self._style_sound_btn()

    def _dial(self, px: int) -> ft.Control:
        """The ring with the remaining time centred in it."""
        return ft.Stack(
            [
                self.ring,
                ft.Container(
                    self.display,
                    alignment=ft.alignment.center,
                    width=px,
                    height=px,
                ),
            ],
            width=px,
            height=px,
        )

    def _controls_row(self, **row_kw) -> ft.Control:
        """Presets, mute and Stop. Rest is automatic; this is the override."""
        return ft.Row(
            [
                self._preset("1m", 60),
                self._preset("1:30", 90),
                self._preset("2m", 120),
                self._preset("3m", 180),
                self.sound_btn,
                self.stop_btn,
            ],
            spacing=4,
            wrap=True,
            **row_kw,
        )

    def build(self) -> ft.Control:
        self._restyle(ring_px=RING_PX, display_pt=DISPLAY_PT, stroke=4)
        return ft.Row(
            [self._dial(RING_PX), self._controls_row()],
            spacing=10,
            vertical_alignment=ft.CrossAxisAlignment.CENTER,
        )

    def build_large(self, caption: str | None = None) -> ft.Control:
        """The same countdown, sized to be read from a metre away.

        Zen mode's rest block. The phone is on the floor or on the bench and
        Alex is standing over it: at 14 pt the seconds left are a squint, which
        is why he picks the phone up mid-rest in the first place.

        It returns the controls `build()` returns, not copies of them —
        `_tick_loop` counts down by mutating `self.display` and `self.ring`, so
        a copy would freeze at the value it was cloned with. Only one of the two
        layouts is ever mounted at a time, which is what makes sharing safe.

        It stays this size even with no rest running, which looks like waste and
        is not. Shrinking when idle would mean re-rendering on `start()` and
        `stop()`, and a rebuild while a set is being typed steals the focus and
        the caret mid-number — the same trap `_set_row.touched()` exists to dodge.
        A steady dial that reads REST, then the seconds, then GO! costs some
        pixels and cannot eat a keystroke.
        """
        self._restyle(ring_px=RING_PX_LARGE, display_pt=DISPLAY_PT_LARGE, stroke=8)
        children: list[ft.Control] = [self._dial(RING_PX_LARGE)]
        if caption:
            children.append(
                ft.Text(
                    caption,
                    size=10,
                    color=C.text_muted,
                    weight=ft.FontWeight.W_700,
                    text_align=ft.TextAlign.CENTER,
                )
            )
        children.append(self._controls_row(alignment=ft.MainAxisAlignment.CENTER))
        return ft.Container(
            content=ft.Column(
                children,
                horizontal_alignment=ft.CrossAxisAlignment.CENTER,
                spacing=8,
                tight=True,
            ),
            bgcolor=C.bg_page,
            border=ft.border.all(1, C.border),
            border_radius=Radius.lg,
            padding=ft.padding.symmetric(horizontal=12, vertical=14),
            alignment=ft.alignment.center,
        )
